#!/usr/bin/env python3
"""assets/mudslogel_idle.png -> ../dsl_win_assets.h (one PNG per frame as C byte arrays). Run after the sheet changes;
the header is committed. mudslogel_idle.png = the game's Mud Slogel idle animation, 5 frames of 32x36 side by side
(the same sheet the wiki shows)."""
import io, os
from PIL import Image
d = os.path.dirname(os.path.abspath(__file__))
sheet = Image.open(os.path.join(d, 'mudslogel_idle.png')).convert('RGBA')
n = sheet.width // 32
out = ['// generated by assets/gen_assets.py from assets/mudslogel_idle.png - do not edit', '#pragma once',
       '#define SLOGEL_FRAMES %d' % n, '#define SLOGEL_W 32', '#define SLOGEL_H %d' % sheet.height]
names = []
for k in range(n):
    b = io.BytesIO(); sheet.crop((32 * k, 0, 32 * k + 32, sheet.height)).save(b, 'PNG', optimize=True); b = b.getvalue()
    rows = [', '.join('0x%02x' % x for x in b[i:i + 20]) for i in range(0, len(b), 20)]
    out.append('static const unsigned char slogel_%d[%d] = {\n    %s };' % (k, len(b), ',\n    '.join(rows)))
    names.append(k)
out.append('static const struct { const unsigned char *png; unsigned len; } slogel_frames[SLOGEL_FRAMES] = { %s };'
           % ', '.join('{ slogel_%d, sizeof slogel_%d }' % (k, k) for k in names))
open(os.path.join(d, '..', 'dsl_win_assets.h'), 'w').write('\n'.join(out) + '\n')
print('wrote dsl_win_assets.h,', n, 'frames')
