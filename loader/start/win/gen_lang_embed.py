#!/usr/bin/env python3
"""gen_lang_embed.py <lang dir> <out.h>: the kit's files\\lang (the loader's <code>.json + setup_<code>.bat, the exact bytes
the kit ships) as a C header for the Windows starter, each file zlib-compressed. The starter puts a missing or different
file back into ROOT\\game\\lang at its start (ds_modded_win.c lang_heal): auto-updates up to 0.1.28 never copied them."""
import os, sys, zlib

src, out = sys.argv[1], sys.argv[2]
names = sorted(n for n in os.listdir(src) if os.path.isfile(os.path.join(src, n)) and n.endswith(('.json', '.bat')))
if not names:
    sys.exit(f'gen_lang_embed: no .json / .bat in {src}')
rows, blobs = [], []
for i, n in enumerate(names):
    if not n.isascii() or '\\' in n or '/' in n or '"' in n:
        sys.exit(f'gen_lang_embed: bad file name {n!r}')
    d = open(os.path.join(src, n), 'rb').read(); z = zlib.compress(d, 9)
    blobs.append(f'static const unsigned char dsl_lang_z{i}[] = {{' + ','.join(str(b) for b in z) + '};')
    rows.append(f'    {{ "{n}", {len(d)}u, {len(z)}u, dsl_lang_z{i} }},')
tmp = out + '.tmp'
with open(tmp, 'w') as f:
    f.write('/* generated by loader/start/win/gen_lang_embed.py from the kit\'s files\\lang: do not edit */\n#pragma once\n')
    f.write('typedef struct { const char *name; unsigned size, zsize; const unsigned char *z; } DslLangFile;\n')
    f.write('\n'.join(blobs) + '\n')
    f.write(f'#define DSL_LANG_N {len(names)}\nstatic const DslLangFile DSL_LANG[DSL_LANG_N] = {{\n' + '\n'.join(rows) + '\n};\n')
os.replace(tmp, out)
print(f'gen_lang_embed: {len(names)} files, {sum(os.path.getsize(os.path.join(src, n)) for n in names)} bytes -> {out}')
