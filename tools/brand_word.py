#!/usr/bin/env python3
"""brand_word.py - draws the word "ModLoader" in the look of the game's title logo and writes it as a C header.

  python3 tools/brand_word.py [--preview <logo.png> <out.png>]

Output: loader/src/dsl_brand_word.h (the PNG bytes, embedded in the loader; dsl_ui.c shows it under the title logo).
Only the word is drawn here: the game's own logo stays the game's (nothing of the game is copied into this repo).

Look (measured on the title logo texture, Img_GameLogo: 356x143 texels, letters in the top 109 rows): Cinzel-like flared capitals, light grey fill
(#DCDCDC) with a brighter rim (#F6F6F6) just inside every edge, a thin dark grey outline (#7A7A7A, about 1 texel) and a
soft dark shadow around the letters (black, about 25 %). Letters drawn in the logo's texel grid; the game draws the logo
texture at 0.64 units per texel (228 x 91 units for 356 x 143 texels): the loader draws the word at the logo's own scale,
so strokes and outline match. Font: ui/fonts/Cinzel.ttf (OFL, weight 900; its lower case are small capitals, so
"ModLoader" gives tall M and L like the logo's tall D and S).
Needs Pillow (any version from 9.1).
"""
import io
import os
import sys

from PIL import Image, ImageChops, ImageDraw, ImageFilter, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
FONT = os.path.join(REPO, 'ui', 'fonts', 'Cinzel.ttf')
OUT_H = os.path.join(REPO, 'loader', 'src', 'dsl_brand_word.h')

WORD = 'ModLoader'
S = 4                       # supersampling
WIDTH = 214                 # word width in logo texels (the logo is 356 wide)
SQUEEZE = 0.92              # horizontal scale of the letters (the logo's capitals are a little narrower than Cinzel's)
TRACK = 0.02                # extra letter spacing, in em
FILL = (220, 220, 220)
RIM = (246, 246, 246)
LINE = (122, 122, 122)
PAD = 4                     # texels around the word (outline + shadow)


def morph(mask, r, grow):
    """dilate (grow) or erode a mask by r pixels (square-ish, MaxFilter / MinFilter, odd sizes)"""
    k = 2 * int(round(r)) + 1
    return mask.filter(ImageFilter.MaxFilter(k) if grow else ImageFilter.MinFilter(k))


def word_mask():
    size = 200
    ft = ImageFont.truetype(FONT, size)
    try:
        ft.set_variation_by_axes([900])
    except Exception:
        pass
    # letters one by one: tracking, then the whole word squeezed horizontally
    glyphs, x = [], 0
    for ch in WORD:
        bb = ft.getbbox(ch)
        adv = ft.getlength(ch)
        glyphs.append((ch, x))
        x += adv + TRACK * size
    w = int(x + size); h = int(size * 1.6)
    m = Image.new('L', (w, h), 0); d = ImageDraw.Draw(m)
    for ch, gx in glyphs:
        d.text((size * 0.3 + gx, size * 0.2), ch, font=ft, fill=255)
    m = m.crop(m.getbbox())
    m = m.resize((max(1, int(m.width * SQUEEZE)), m.height), Image.LANCZOS)
    # to the target width in texels, x S
    tw = WIDTH * S; th = int(round(m.height * tw / m.width))
    return m.resize((tw, th), Image.LANCZOS)


def render():
    core = word_mask()
    p = PAD * S
    mask = Image.new('L', (core.width + 2 * p, core.height + 2 * p), 0); mask.paste(core, (p, p))
    inner = morph(mask, 1.0 * S, False)
    outer = morph(mask, 1.0 * S, True)
    shadow = morph(mask, 1.0 * S, True).filter(ImageFilter.GaussianBlur(1.6 * S))
    shadow = ImageChops.offset(shadow, 0, int(0.8 * S)).point(lambda v: int(v * 0.30))
    W, H = mask.size
    img = Image.new('RGBA', (W, H), (0, 0, 0, 0))
    img.alpha_composite(Image.merge('RGBA', (Image.new('L', (W, H), 0),) * 3 + (shadow,)))
    img.alpha_composite(Image.merge('RGBA', [Image.new('L', (W, H), c) for c in LINE] + [outer.point(lambda v: int(v * 0.9))]))
    img.alpha_composite(Image.merge('RGBA', [Image.new('L', (W, H), c) for c in RIM] + [mask]))
    img.alpha_composite(Image.merge('RGBA', [Image.new('L', (W, H), c) for c in FILL] + [inner]))
    # down to texels (premultiplied, so the transparent edge does not darken)
    small = img.convert('RGBa').resize((W // S, H // S), Image.LANCZOS).convert('RGBA')
    return small


def header(png):
    rows = [', '.join(f'0x{b:02x}' for b in png[i:i + 20]) for i in range(0, len(png), 20)]
    return ('/* dsl_brand_word.h - GENERATED by tools/brand_word.py (do not edit): the word "ModLoader" in the look of the\n'
            '   game\'s title logo, PNG, drawn under the logo by dsl_ui.c (brand_frame). Font: ui/fonts/Cinzel.ttf (OFL). */\n'
            f'static const unsigned char brand_word_png[{len(png)}] = {{\n    ' + ',\n    '.join(rows) + '\n};\n')


def main():
    img = render()
    buf = io.BytesIO(); img.save(buf, 'PNG', optimize=True); png = buf.getvalue()
    open(OUT_H, 'w').write(header(png))
    print(f'{OUT_H}: {img.width}x{img.height} texels, {len(png)} bytes PNG')
    if len(sys.argv) == 4 and sys.argv[1] == '--preview':
        logo = Image.open(sys.argv[2]).convert('RGBA')
        sx, sy = 228 / 356, 91 / 143                       # the game's draw scale of the logo texture
        k = 3                                              # preview zoom
        lw, lh = int(logo.width * sx * k), int(logo.height * sy * k)
        ww, wh = int(img.width * sx * k), int(img.height * sy * k)
        out = Image.new('RGBA', (lw + 40, lh + wh + 40), (36, 36, 40, 255))
        out.alpha_composite(logo.resize((lw, lh), Image.LANCZOS), (20, 10))
        out.alpha_composite(img.resize((ww, wh), Image.LANCZOS), (20 + (lw - ww) // 2, 10 + int(110 * sy * k)))
        out.save(sys.argv[3]); print('preview', sys.argv[3])


if __name__ == '__main__':
    main()
